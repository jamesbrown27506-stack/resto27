/**
 * The notification sound — which ones exist, and how a stored value becomes
 * a playable URL.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  ONE SETTING, TWO KINDS OF VALUE.
 *
 *  `settings.notification_sound` holds either:
 *    · a BUILT-IN name — "chime", "tri-tone" — which lives in public/sounds
 *      and ships with the app; or
 *    · a URL — an audio file the administrator uploaded to object storage.
 *
 *  Keeping both in one column means every reader (the realtime provider, the
 *  settings preview, a future email digest) resolves them the same way
 *  through `notificationSoundUrl`, and nothing has to know which kind it got.
 *  A value that is neither — a name whose file was deleted — degrades to the
 *  default rather than to silence.
 * ─────────────────────────────────────────────────────────────────────────
 *
 * NOT `server-only`: the browser is the only thing that ever plays these, so
 * both the provider and the admin settings screen import it directly.
 */

export interface BuiltInSound {
  value: string;
  label: string;
}

/** Shipped in public/sounds, generated by scripts/generate-sounds.mjs. */
export const BUILT_IN_SOUNDS: readonly BuiltInSound[] = [
  { value: "chime", label: "Chime (default)" },
  { value: "ding", label: "Ding" },
  { value: "pop", label: "Pop" },
  { value: "triple", label: "Triple ding" },
  { value: "alert", label: "Alert" },
  { value: "tri-tone", label: "Tri-tone (iPhone-style)" },
];

export const DEFAULT_SOUND = "chime";

/** True when the stored value is an uploaded file rather than a built-in. */
export function isCustomSound(value: string | null | undefined): boolean {
  if (!value) return false;
  return /^https?:\/\//i.test(value) || value.startsWith("/storage/");
}

/**
 * The URL to hand to `new Audio(...)`.
 *
 * An unknown built-in name falls back to the default: a sound file that was
 * renamed or removed should not silence every notification on the platform.
 */
export function notificationSoundUrl(value: string | null | undefined): string {
  if (!value) return `/sounds/${DEFAULT_SOUND}.wav`;
  if (isCustomSound(value)) return value;
  const known = BUILT_IN_SOUNDS.some((s) => s.value === value);
  return `/sounds/${known ? value : DEFAULT_SOUND}.wav`;
}
