/**
 * PLACING AN ORDER — the one path by which a customer's basket becomes a row.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  THE CLIENT SENDS IDS AND QUANTITIES. NOTHING ELSE IS BELIEVED.
 *
 *  Not the price, not the dish name, not the discount, not the total. Every
 *  one of those is re-read from the database here, exactly as
 *  `createTableOrder` does for a waiter. A Server Action is a public POST
 *  endpoint: whatever the basket component computed is a suggestion from an
 *  attacker-controlled process, and the only figures that reach `orders` are
 *  the ones this function derived.
 *
 *  A tampered request can order a lot of food. It cannot reprice it.
 * ─────────────────────────────────────────────────────────────────────────
 *
 * GUESTS MAY ORDER (§2). `customer_id` is null for them and the delivery name
 * and phone carry the identity — forcing registration before someone can buy
 * is the single biggest drop-off in food ordering.
 */

export interface CheckoutLine {
  menuItemId: string;
  quantity: number;
  optionIds: string[];
  notes?: string | null;
}

export interface CheckoutInput {
  restaurantId: string;
  type: "delivery" | "pickup";
  lines: CheckoutLine[];

  /** Required for delivery, ignored for pickup. */
  addressId?: string | null;
  deliveryName?: string;
  deliveryPhone?: string;
  deliveryAddress?: string;
  deliveryQuartier?: string | null;
  deliveryLandmark?: string | null;

  promoCode?: string | null;
  loyaltyPoints?: number;
  paymentMethod?: string;
  notes?: string | null;
  /** ISO timestamp — when the customer wants the order delivered/picked up. */
  scheduledFor?: string | null;
  /**
   * One UUID per checkout ATTEMPT, generated by the client.
   *
   * Sending the same key twice returns the first order instead of creating a
   * second. This is what makes a retry safe when the response was lost rather
   * than the request — the case a disabled button cannot reach, because the
   * page has been reloaded by then. See migration 0047.
   */
  idempotencyKey?: string | null;
}

/**
 * A client-supplied idempotency key is untrusted input that reaches a unique
 * index, so it is shape-checked before use. Anything that is not a UUID is
 * treated as absent rather than rejected — the order should still go through.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
function isUuid(value: string | null | undefined): boolean {
  return typeof value === "string" && UUID_RE.test(value);
}

/**
 * "That column does not exist", in both the shapes this codebase has seen.
 *
 * Duplicated from customer-actions deliberately, exactly as the other copies
 * are: that module is "use server", and importing it here to share eight lines
 * would drag its whole dependency graph along.
 *
 * It matters on THIS path more than most. Migration 0047 adds
 * `orders.idempotency_key`, and this repository has a history of code shipping
 * ahead of its SQL — 0039 and 0040 sat unapplied for weeks. If that happened
 * here without this guard, every order on the platform would fail at the
 * insert. Tolerating the missing column makes the deploy order irrelevant:
 * duplicate protection simply stays off until the SQL is run.
 */
function isMissingColumn(error: { code?: string; message?: string } | null, column: string) {
  if (!error) return false;
  const known = error.code === "42703" || error.code === "PGRST204";
  return known && (error.message ?? "").includes(column);
}

/** Reason CODES, not prose — checkout is bilingual and the client translates. */
export type CheckoutResult =
  | { ok: true; orderId: string; reference: string }
  | { ok: false; reason: string; detail?: string };

const MAX_QTY_PER_LINE = 50;

/**
 * The cart restaurant's order capabilities, for the checkout screen.
 *
 * The basket lives in localStorage, so the checkout page's Server Component
 * cannot know which restaurant it belongs to — the client asks here, once, so
 * it can disable a mode the kitchen does not offer instead of letting the
 * customer fill the whole form and only then rejecting it.
 */
export async function getRestaurantOrderCapabilities(
  restaurantId: string,
): Promise<{
  acceptsDelivery: boolean;
  acceptsPickup: boolean;
  /** Where pickup customers collect the order (neighbourhood). */
  quartier: string;
  /** Estimated delivery time in minutes, for the delivery hint. */
  deliveryEstimateMin: number;
  /** Delivery-only minimum order in XAF. Pickup has no minimum. */
  minimumOrder: number;
  /**
   * The delivery fee band the restaurant advertises (migration 0035).
   *
   * Both 0 means "not declared", and checkout falls back to the old
   * "the restaurant will tell you when it confirms" note. When they are set,
   * the customer is given real numbers to budget against BEFORE committing —
   * which is the whole point of asking a restaurant to declare them.
   */
  minDeliveryFee: number;
  maxDeliveryFee: number;
} | null> {
  const supabase = createAdminClient();

  const { data } = await supabase
    .from("restaurants")
    .select(
      "accepts_delivery, accepts_pickup, status, delivery_estimate_min, minimum_order, min_delivery_fee, max_delivery_fee, quartiers ( name )",
    )
    .eq("id", restaurantId)
    .maybeSingle();

  if (!data || data.status !== "active") return null;
  return {
    acceptsDelivery: Boolean(data.accepts_delivery),
    acceptsPickup: Boolean(data.accepts_pickup),
    quartier: (data.quartiers as { name: string }[] | null)?.[0]?.name ?? "",
    deliveryEstimateMin: Number(data.delivery_estimate_min) || 0,
    minimumOrder: Number(data.minimum_order) || 0,
    minDeliveryFee: Number(data.min_delivery_fee) || 0,
    maxDeliveryFee: Number(data.max_delivery_fee) || 0,
  };
}

export async function placeOrder(input: CheckoutInput): Promise<CheckoutResult> {
  const supabase = createAdminClient();

  // ── Rate limit ────────────────────────────────────────────────────────
  // Placing an order is a real write: rows, a notification, an email, stock
  // decrements. A script could drive it as a spam/DOS vector against a
  // kitchen. 10 orders in 10 minutes per person/IP is beyond any human cadence.
  const profile = await getCurrentProfile();
  if (!profile) return { ok: false, reason: "loginRequired" };
  const limited = await rateLimit({
    key: "checkout:place",
    limit: 10,
    windowMs: 10 * 60_000,
    identifier: profile?.id,
  });
  if (!limited.ok) return { ok: false, reason: "rateLimited" };

  /*
    An attempt this client has already completed returns that order rather than
    starting a second one. Checked before any validation or stock work, because
    a retry should be cheap and must not decrement stock twice.
  */
  let idempotencyKey = isUuid(input.idempotencyKey) ? input.idempotencyKey! : null;
  if (idempotencyKey) {
    const { data: already, error: lookupError } = await supabase
      .from("orders")
      .select("id, reference")
      .eq("idempotency_key", idempotencyKey)
      .maybeSingle();

    if (isMissingColumn(lookupError, "idempotency_key")) {
      // Migration 0047 has not been run. Place the order without the key
      // rather than refusing to take it.
      idempotencyKey = null;
    } else if (already) {
      return { ok: true, orderId: already.id, reference: already.reference };
    }
  }

  if (!input.lines?.length) return { ok: false, reason: "emptyBasket" };
  const paymentMethod = input.paymentMethod === "wallet" ? "wallet" : "mobile_money";
  if (paymentMethod === "wallet" && !profile) return { ok: false, reason: "loginRequired" };
  if (input.type !== "delivery" && input.type !== "pickup") {
    return { ok: false, reason: "badType" };
  }

  // ── The restaurant must actually be open for business ───────────────────
  const { data: restaurantRow } = await supabase
    .from("restaurants")
    .select("id, name, status, is_accepting_orders, accepts_delivery, accepts_pickup, minimum_order")
    .eq("id", input.restaurantId)
    .maybeSingle();

  const restaurant = restaurantRow as {
    id: string;
    name: string;
    status: string;
    is_accepting_orders: boolean;
    accepts_delivery: boolean;
    accepts_pickup: boolean;
    minimum_order: number;
  } | null;

  if (!restaurant || restaurant.status !== "active") return { ok: false, reason: "restaurantUnavailable" };
  if (!restaurant.is_accepting_orders) return { ok: false, reason: "notAcceptingOrders" };
  if (input.type === "delivery" && !restaurant.accepts_delivery) return { ok: false, reason: "noDelivery" };
  if (input.type === "pickup" && !restaurant.accepts_pickup) return { ok: false, reason: "noPickup" };

  // ── Reprice every line from the database ────────────────────────────────
  const itemIds = [...new Set(input.lines.map((l) => l.menuItemId))];
  const { data: menuRows } = await supabase
    .from("menu_items")
    .select("id, name, price, is_available, track_stock, stock_quantity, low_stock_threshold")
    // Scoped to THIS restaurant: without it, an id from another tenant's menu
    // would be priced and sold by a kitchen that has never heard of it.
    .eq("restaurant_id", input.restaurantId)
    .in("id", itemIds);

  const menu = new Map(
    ((menuRows ?? []) as {
      id: string;
      name: string;
      price: number;
      is_available: boolean;
      track_stock: boolean;
      stock_quantity: number | null;
      low_stock_threshold: number | null;
    }[]).map((m) => [m.id, m]),
  );

  const optionIds = [...new Set(input.lines.flatMap((l) => l.optionIds ?? []))];
  const { data: optionRows } = optionIds.length
    ? await supabase
        .from("menu_options")
        // Only options belonging to this restaurant's menu items, proven by the
        // join — menu_options has no restaurant_id of its own.
        .select("id, name, price_delta, is_available, group_id, menu_option_groups!inner(menu_item_id)")
        .in("id", optionIds)
    : { data: [] };

  const options = new Map(
    ((optionRows ?? []) as unknown as {
      id: string;
      name: string;
      price_delta: number;
      is_available: boolean;
      menu_option_groups: { menu_item_id: string };
    }[]).map((o) => [o.id, o]),
  );

  let subtotal = 0;
  const itemInserts: Record<string, unknown>[] = [];

  for (const line of input.lines) {
    const item = menu.get(line.menuItemId);
    if (!item) return { ok: false, reason: "itemGone" };
    if (!item.is_available) return { ok: false, reason: "itemSoldOut", detail: item.name };

    if (!Number.isInteger(line.quantity) || line.quantity < 1 || line.quantity > MAX_QTY_PER_LINE) {
      return { ok: false, reason: "badQuantity" };
    }
    if (item.track_stock && item.stock_quantity !== null && item.stock_quantity < line.quantity) {
      return { ok: false, reason: "notEnoughStock", detail: item.name };
    }

    const chosen: { name: string; price_delta: number }[] = [];
    for (const id of line.optionIds ?? []) {
      const option = options.get(id);
      // An option that does not exist, is unavailable, or belongs to a
      // DIFFERENT dish is refused rather than silently dropped — dropping it
      // would serve a customer something other than what they chose.
      if (!option) return { ok: false, reason: "optionGone" };
      if (!option.is_available) return { ok: false, reason: "optionUnavailable", detail: option.name };
      if (option.menu_option_groups?.menu_item_id !== line.menuItemId) {
        return { ok: false, reason: "optionMismatch" };
      }
      chosen.push({ name: option.name, price_delta: option.price_delta });
    }

    const unitPrice = item.price + chosen.reduce((sum, o) => sum + o.price_delta, 0);
    if (unitPrice < 0) return { ok: false, reason: "badPrice" };

    subtotal += unitPrice * line.quantity;
    itemInserts.push({
      menu_item_id: line.menuItemId,
      // Snapshotted (§12): the receipt still reads correctly after the dish is
      // renamed, repriced or deleted.
      name: item.name,
      unit_price: unitPrice,
      quantity: line.quantity,
      options_label: chosen.map((o) => o.name).join(" · ") || null,
      notes: line.notes?.trim() || null,
    });
  }

  if (subtotal <= 0) return { ok: false, reason: "emptyBasket" };

  // The restaurant's own floor, checked on food only — a minimum that a
  // delivery fee could satisfy is not a minimum.
  if (input.type === "delivery" && restaurant.minimum_order > 0 && subtotal < restaurant.minimum_order) {
    return { ok: false, reason: "belowMinimum", detail: String(restaurant.minimum_order) };
  }

  // ── Promotion, re-validated ─────────────────────────────────────────────
  let discount = 0;
  let promoCode: string | null = null;
  let promoId: string | null = null;

  /** One validation/application pass, shared by both promo sources below. */
  function applyPromo(promo: {
    id: string;
    code: string;
    discount_type: string;
    discount_value: number;
    min_order: number;
    max_discount: number | null;
    starts_at: string | null;
    ends_at: string | null;
    usage_limit: number | null;
    used_count: number;
    is_active: boolean;
  }): boolean {
    // Refused, not ignored. Dropping an invalid code and charging full price
    // is how someone pays more than the screen told them they would.
    if (!promo.is_active) return false;

    const now = Date.now();
    if (promo.starts_at && now < new Date(promo.starts_at).getTime()) return false;
    if (promo.ends_at && now > new Date(promo.ends_at).getTime()) return false;
    if (promo.usage_limit !== null && promo.used_count >= promo.usage_limit) return false;
    if (subtotal < promo.min_order) return false;

    discount = discountFor(promo, subtotal);
    promoCode = promo.code;
    promoId = promo.id;
    return true;
  }

  if (input.promoCode?.trim()) {
    const code = input.promoCode.trim().toUpperCase();

    // First the restaurant's own codes (0006)…
    const { data: promoRow } = await supabase
      .from("promotions")
      .select("id, code, discount_type, discount_value, min_order, max_discount, starts_at, ends_at, usage_limit, used_count, is_active")
      .eq("restaurant_id", input.restaurantId)
      .eq("code", code)
      .maybeSingle();

    const promo = promoRow as {
      id: string;
      code: string;
      discount_type: string;
      discount_value: number;
      min_order: number;
      max_discount: number | null;
      starts_at: string | null;
      ends_at: string | null;
      usage_limit: number | null;
      used_count: number;
      is_active: boolean;
    } | null;

    if (promo && applyPromo(promo)) {
      // Applied — done.
    } else {
      // …then the PLATFORM's codes (migration 0023), but only while the kill
      // switch is on. A restaurant code that exists but is inactive/expired
      // must not silently fall through to a platform code of the same name;
      // only a code with no restaurant match gets the platform lookup.
      const { data: platformSetting } = await supabase
        .from("settings")
        .select("value")
        .eq("key", "platform_coupons_enabled")
        .maybeSingle();

      if (platformSetting?.value === "true" && !promo) {
        const { data: platformRow } = await supabase
          .from("platform_coupons")
          .select("id, code, discount_type, discount_value, min_order, max_discount, starts_at, ends_at, usage_limit, used_count, is_active")
          .eq("code", code)
          .maybeSingle();

        const platformPromo = platformRow as {
          id: string;
          code: string;
          discount_type: string;
          discount_value: number;
          min_order: number;
          max_discount: number | null;
          starts_at: string | null;
          ends_at: string | null;
          usage_limit: number | null;
          used_count: number;
          is_active: boolean;
        } | null;

        if (platformPromo && applyPromo(platformPromo)) {
          // Applied — done.
        } else {
          // No match, or the code exists but is not usable right now. Either
          // way the customer gets told the code was refused, never charged
          // full price silently.
          return { ok: false, reason: "promoInvalid" };
        }
      } else if (promo) {
        // A restaurant code exists but did not pass validation — refuse.
        return { ok: false, reason: "promoInvalid" };
      }
    }
  }

  // ── Loyalty, re-validated ───────────────────────────────────────────────
  const config = await getCartConfig();

  let pointsUsed = 0;
  let loyaltyValue = 0;

  if (config.loyaltyEnabled && profile && (input.loyaltyPoints ?? 0) > 0) {
    const requested = Math.floor(input.loyaltyPoints ?? 0);
    const { data: balanceData } = await supabase.rpc("loyalty_balance", { p_profile: profile.id });
    const balance = Number(balanceData ?? 0);

    if (requested > balance) return { ok: false, reason: "notEnoughPoints" };
    if (requested < config.minRedeem) return { ok: false, reason: "belowMinPoints", detail: String(config.minRedeem) };

    // Capped at the food value: points must not pay the service charge or the
    // rider, and must never drive the total below zero.
    const netFood = Math.max(0, subtotal - discount);
    loyaltyValue = Math.min(requested * config.pointValue, netFood);
    pointsUsed = config.pointValue > 0 ? Math.ceil(loyaltyValue / config.pointValue) : 0;
  }

  const totals = computeTotals({
    subtotal,
    discount,
    serviceChargePercent: config.serviceChargePercent,
    // Quoted by the restaurant when it confirms (§4). Never guessed here.
    deliveryFee: 0,
    loyaltyValue,
  });

  // ── Delivery details ────────────────────────────────────────────────────
  let deliveryName = input.deliveryName?.trim() ?? profile?.name ?? "";
  let deliveryPhone = input.deliveryPhone?.trim() ?? profile?.phone ?? "";
  let addressLine = input.deliveryAddress?.trim() ?? "";
  let quartier = input.deliveryQuartier?.trim() || null;
  let landmark = input.deliveryLandmark?.trim() || null;

  if (input.type === "delivery" && input.addressId && profile) {
    // A saved address is re-read rather than trusted from the form, and scoped
    // to the person asking — an id from someone else's account must not
    // resolve into this order.
    const { data: saved } = await supabase
      .from("customer_addresses")
      .select("recipient_name, phone, address_line, landmark, quartiers ( name )")
      .eq("id", input.addressId)
      .eq("profile_id", profile.id)
      .maybeSingle();

    const row = saved as unknown as {
      recipient_name: string | null;
      phone: string | null;
      address_line: string;
      landmark: string | null;
      quartiers: { name: string }[] | null;
    } | null;

    if (!row) return { ok: false, reason: "addressNotFound" };

    deliveryName = row.recipient_name?.trim() || deliveryName;
    deliveryPhone = row.phone?.trim() || deliveryPhone;
    addressLine = row.address_line;
    quartier = row.quartiers?.[0]?.name ?? quartier;
    landmark = row.landmark ?? landmark;
  }

  if (!deliveryName) return { ok: false, reason: "nameRequired" };
  if (!deliveryPhone) return { ok: false, reason: "phoneRequired" };
  if (input.type === "delivery" && !addressLine) return { ok: false, reason: "addressRequired" };

  /*
    REGISTER A NEIGHBOURHOOD NOBODY HAS TYPED BEFORE.

    `orders.delivery_quartier` is plain text — the order snapshots the name
    the customer gave, and nothing here depends on a foreign key. But the
    checkout box is a datalist, and a datalist is only as useful as the list
    behind it: a quartier typed by one customer should be a suggestion for
    the next, exactly as it is on the restaurant application.

    Deliberately fire-and-forget. This is a convenience for future orders,
    not part of THIS order being valid — a failure here must never cost
    someone their basket, so it is awaited only to keep the request alive and
    its result is ignored.
  */
  if (input.type === "delivery" && quartier && !input.addressId) {
    const areaId = await defaultServiceAreaId();
    if (areaId) {
      await resolveOrCreateQuartier(quartier, areaId).catch(() => null);
    }
  }

  // ── Scheduling ──────────────────────────────────────────────────────────
  let scheduledFor: string | null = null;
  if (input.scheduledFor) {
    const when = new Date(input.scheduledFor);
    if (Number.isNaN(when.getTime())) return { ok: false, reason: "badSchedule" };
    if (when.getTime() <= Date.now() + 60_000) return { ok: false, reason: "scheduleTooSoon" };
    if (when.getTime() > Date.now() + 7 * 86_400_000) return { ok: false, reason: "scheduleTooFar" };
    scheduledFor = when.toISOString();
  }

  // ── Write ───────────────────────────────────────────────────────────────
  const reference = `CMD-${randomUUID().slice(0, 6).toUpperCase()}`;

  /*
    Built once so the insert can be replayed without the key if PostgREST
    reports it does not know the column — see `isMissingColumn`.
  */
  const orderRow = {
    reference,
    restaurant_id: input.restaurantId,
    customer_id: profile?.id ?? null,
    type: input.type,
    // PENDING, not confirmed. The restaurant accepts it — that is what §4's
    // whole flow is about, and it is where the delivery fee gets quoted.
    status: "pending",
    subtotal: totals.subtotal,
    discount_amount: totals.discount,
    service_charge_percent: config.serviceChargePercent,
    service_charge: totals.serviceCharge,
    loyalty_points_used: pointsUsed,
    loyalty_value: totals.loyaltyValue,
    total: totals.total,
    delivery_fee: 0,
    promo_code: promoCode,
    delivery_name: deliveryName,
    delivery_phone: deliveryPhone,
    delivery_address: input.type === "delivery" ? addressLine : null,
    delivery_quartier: input.type === "delivery" ? quartier : null,
    delivery_landmark: input.type === "delivery" ? landmark : null,
    payment_method: paymentMethod,
    notes: input.notes?.trim() || null,
    scheduled_for: scheduledFor,
  };

  // Assigned to a const before use, exactly as createOwnReservation does for
  // its own migration fallback: an inline literal would trip the client's
  // excess-property check against the pre-0047 generated row type.
  const rowWithKey = { ...orderRow, idempotency_key: idempotencyKey };

  let created: { id: string; reference: string } | null = null;
  let error = null as { code?: string; message?: string } | null;

  {
    const attempt = await supabase
      .from("orders")
      .insert(idempotencyKey ? rowWithKey : orderRow)
      .select("id, reference")
      .single();
    created = attempt.data as { id: string; reference: string } | null;
    error = attempt.error;

    if (isMissingColumn(error, "idempotency_key")) {
      // 0047 not applied. Take the order anyway: duplicate protection stays
      // off until the SQL is run, which beats refusing to sell.
      console.warn(
        "[checkout:placeOrder] orders.idempotency_key is missing — run migration 0047. Order placed without duplicate protection.",
      );
      idempotencyKey = null;
      const retry = await supabase
        .from("orders")
        .insert(orderRow)
        .select("id, reference")
        .single();
      created = retry.data as { id: string; reference: string } | null;
      error = retry.error;
    }
  }

  if (error || !created) {
    /*
      23505 is the unique violation on orders_idempotency_key_uidx: two
      requests carrying the same key raced, and the other one won. That is a
      success for this caller — the order exists — so return it rather than
      reporting a failure the customer would respond to by ordering again.
    */
    if (error?.code === "23505" && idempotencyKey) {
      const { data: winner } = await supabase
        .from("orders")
        .select("id, reference")
        .eq("idempotency_key", idempotencyKey)
        .maybeSingle();
      if (winner) return { ok: true, orderId: winner.id, reference: winner.reference };
    }
    console.error("[checkout:placeOrder]", error?.message);
    return { ok: false, reason: "failed" };
  }

  const { error: itemsError } = await supabase
    .from("order_items")
    .insert(itemInserts.map((i) => ({ ...i, order_id: created.id })));

  if (itemsError) {
    // An order without its lines is worse than no order: the kitchen would see
    // an empty ticket and the customer would be charged for it. Roll back.
    console.error("[checkout:placeOrder] items", itemsError.message);
    await supabase.from("orders").delete().eq("id", created.id);
    return { ok: false, reason: "failed" };
  }

  // Payment is deliberately deferred until the restaurant confirms that the
  // requested dishes are available. The selected wallet is charged only then.

  // ── Everything below is non-fatal ───────────────────────────────────────
  // The order exists and the customer has been told so. A failed counter or
  // ledger row must never retract a placed order; it is a reconciliation
  // problem, not a checkout problem.

  await supabase.from("order_status_history").insert({
    order_id: created.id,
    status: "pending",
    by_name: deliveryName,
    note: "Order placed",
  });

  const lowStockNotified = new Set<string>();
  for (const line of input.lines) {
    const item = menu.get(line.menuItemId);
    if (item?.track_stock && item.stock_quantity !== null) {
      const remaining = Math.max(0, item.stock_quantity - line.quantity);
      await supabase
        .from("menu_items")
        .update({ stock_quantity: remaining })
        .eq("id", line.menuItemId)
        .eq("restaurant_id", input.restaurantId);

      // Stock crossed its threshold because of THIS order → the branch should
      // know, once per item, not once per line.
      if (
        item.low_stock_threshold !== null &&
        remaining <= item.low_stock_threshold &&
        item.stock_quantity > item.low_stock_threshold &&
        !lowStockNotified.has(item.id)
      ) {
        lowStockNotified.add(item.id);
        await notify({
          event: "low_stock",
          tone: "warning",
          restaurantId: input.restaurantId,
          href: "/m/menu",
          // The item name keys the push collapse tag: two dishes running low
          // are two banners, while the same dish dropping again replaces its
          // own earlier warning.
          params: { itemName: item.name, count: remaining, reference: item.name },
        });
      }
    }
  }

  if (promoId) {
    // The counter `usage_limit` is checked against. Without this increment the
    // limit is decorative — a single-use code would be redeemable for ever.
    // Read-then-write rather than an atomic bump because PostgREST has no
    // expression update; two simultaneous redemptions of the last use is a
    // narrow race worth accepting over a stored procedure for this.
    const { data: current } = await supabase
      .from("promotions")
      .select("used_count")
      .eq("id", promoId)
      .maybeSingle();

    if (current) {
      await supabase
        .from("promotions")
        .update({ used_count: ((current.used_count as number | undefined) ?? 0) + 1 })
        .eq("id", promoId);

      await supabase.from("promotion_redemptions").insert({
        promotion_id: promoId,
        order_id: created.id,
        customer_id: profile?.id ?? null,
        amount: totals.discount,
      });
    } else {
      // The promo came from the PLATFORM coupon table — its id is not a
      // promotion_redemptions fk. Bump the platform counter instead.
      const { data: couponRow } = await supabase
        .from("platform_coupons")
        .select("used_count")
        .eq("id", promoId)
        .maybeSingle();

      await supabase
        .from("platform_coupons")
        .update({ used_count: ((couponRow?.used_count as number | undefined) ?? 0) + 1 })
        .eq("id", promoId);
    }
  }

  if (pointsUsed > 0 && profile) {
    await supabase.from("loyalty_ledger").insert({
      profile_id: profile.id,
      order_id: created.id,
      restaurant_id: input.restaurantId,
      points: -pointsUsed,
      kind: "redeem",
      note: `Commande ${created.reference}`,
    });
  }

  /**
   * POINTS ARE EARNED ON DELIVERY, NOT HERE.
   *
   * Awarding them at checkout would pay for orders that are later cancelled,
   * and the natural exploit is to order, collect, cancel, repeat. The earn row
   * belongs to whatever marks an order `delivered`.
   */

  revalidatePath("/orders");
  revalidatePath("/account");

  // ── Notification triggers ────────────────────────────────────────────
  // The order is written; everything below is news about it. Non-fatal.
  //
  // PAYMENT FIRST: the kitchen hears about an order when there is something
  // for it to do. A delivery order needs its fee quoted before the customer
  // can pay, so the restaurant is told now. A pickup order is announced by
  // settlePayment the moment the customer's payment is confirmed — ringing
  // the kitchen for an order nobody has paid for invites cooking it.
  if (input.type === "delivery") {
    await notify({
      event: "new_order",
      tone: "success",
      restaurantId: input.restaurantId,
      href: `/m/orders/${created.id}`,
      params: {
        reference: created.reference,
        customerName: deliveryName,
        amount: totals.total,
      },
    });
  }

  // Registered customers get a confirmation; guests have no profile to reach.
  if (profile) {
    await notify({
      event: "order_status",
      tone: "info",
      customerId: profile.id,
      href: `/orders/${created.id}`,
      params: {
        status: "pending",
        reference: created.reference,
        restaurantName: restaurant.name,
        orderType: input.type,
      },
    });
  }

  return { ok: true, orderId: created.id, reference: created.reference };
}
