import type { MetadataRoute } from "next";
import { getBranding } from "@/lib/branding";

/**
 * The web app manifest, generated — not a static file.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  WHY THIS IS A ROUTE AND NOT public/manifest.json
 *
 *  The manifest is what decides the name and icon of the installed app — and
 *  both come from /a/settings (brand_name, brand_icon_url). A static file
 *  could only ever show the defaults; uploading an app icon in the admin
 *  panel would change a database row and nothing on any home screen.
 *
 *  This route reads branding per request. `force-dynamic` matters: without it
 *  Next would try to prerender the route at build time, baking in the
 *  defaults forever and silently swallowing the DB call's failure.
 *
 *  When brand_icon_url is set it is declared twice — once as 192×192, once as
 *  512×512 — with purpose "any maskable", the combination Chrome's install
 *  criteria and the home-screen masking both want. The uploaded file is a
 *  single square image; browsers scale it to the declared size.
 * ─────────────────────────────────────────────────────────────────────────
 */
export const dynamic = "force-dynamic";

export default async function manifest(): Promise<MetadataRoute.Manifest> {
  const brand = await getBranding();
  const icon = brand.iconUrl;

  return {
    name: brand.name,
    short_name: brand.name,
    description: brand.tagline,
    id: "/",
    start_url: "/",
    scope: "/",
    display: "standalone",
    background_color: "#F7F4ED",
    theme_color: "#5f7257",
    icons: icon
      ? [
          // Next's Icon type takes ONE purpose per entry (not the spec's
          // space-separated list): "maskable" on the small entry covers the
          // home-screen masking, and the plain 512 entry defaults to "any",
          // which is the icon Chrome's install criteria actually checks.
          { src: icon, sizes: "192x192", type: "image/png", purpose: "maskable" },
          { src: icon, sizes: "512x512", type: "image/png" },
        ]
      : [
          // The shipped default — generated by scripts/generate-app-icon.mjs.
          { src: "/app-icon-192.png", sizes: "192x192", type: "image/png" },
          { src: "/app-icon-512.png", sizes: "512x512", type: "image/png" },
        ],
  };
}
